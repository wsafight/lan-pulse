package com.lanpulse.mobile

enum class MobileLanguage(
    val code: String,
    val displayName: String,
) {
    En("en", "English"),
    ZhCn("zh-CN", "中文"),
    ;

    fun strings(): MobileStrings = when (this) {
        En -> ENGLISH_STRINGS
        ZhCn -> CHINESE_STRINGS
    }

    companion object {
        fun fromCode(code: String?): MobileLanguage = entries.firstOrNull { it.code == code } ?: En
    }
}

